# Browser check of product photos. Run from apps/web:  mkdir -p shots && python e2e/photos-flow.py
import time, sys
from playwright.sync_api import sync_playwright
run = hex(int(time.time()))[2:]
import os
B = os.environ.get('WEB_URL', 'http://localhost:3001')
res = []; errs = []
def ok(n, c): res.append(bool(c)); print(('  PASS ' if c else '  FAIL ') + n, flush=True)
with sync_playwright() as p:
    b = p.chromium.launch(args=['--no-sandbox'])
    pg = b.new_page(viewport={'width': 1440, 'height': 900})
    pg.on('console', lambda m: errs.append(m.text) if m.type == 'error' else None)
    pg.set_default_timeout(15000)
    pg.goto(B + '/register')
    pg.get_by_label('Shop name').fill(f'Photo Test {run}'); pg.get_by_role('button', name='Continue').click()
    pg.get_by_label('Your name').fill('Photo Owner'); pg.get_by_label('Mobile number').fill('0715556667')
    pg.get_by_label('Email').fill(f'photo-{run}@demo.lk'); pg.get_by_label('Password', exact=True).fill('Photo@12345')
    pg.get_by_role('button', name='Continue').click(); pg.get_by_label('Branch name').fill('Main Street')
    pg.get_by_role('button', name='Create my shop').click(); pg.wait_for_url('**/dashboard')

    pg.goto(B + '/products/new')
    pg.get_by_label('Name', exact=True).fill('Galaxy A54')
    pg.get_by_label('Option', exact=True).fill('128GB Awesome Navy')
    pg.get_by_label('SKU', exact=True).fill(f'A54-{run}')
    pg.get_by_label('Price (Rs)', exact=True).fill('98500')
    pg.screenshot(path='shots/1-empty-picker.png', full_page=True)
    pg.get_by_label('Choose product photos').set_input_files(['e2e/img/phone-front.jpg', 'e2e/img/phone-back.png'])
    pg.locator('figure img').nth(1).wait_for()
    ok('two photos previewed before saving', pg.locator('figure').count() == 2)
    pg.get_by_label('Choose product photos').set_input_files(['e2e/img/not-an-image.txt'])
    pg.get_by_text('use a JPEG, PNG or WebP photo').wait_for()
    ok('a non-image file is refused with a clear message', True)
    pg.locator('figure').nth(1).hover()
    pg.get_by_role('button', name='Make photo 2 the cover').click()
    pg.screenshot(path='shots/2-picker-filled.png', full_page=True)
    pg.get_by_role('button', name='Save product').click()
    pg.get_by_role('heading', name='Galaxy A54').wait_for()
    pg.locator('figure img').nth(1).wait_for()
    ok('product saved with 2 photos', pg.locator('figure').count() == 2)
    dims = pg.evaluate("""() => Promise.all([...document.querySelectorAll('figure img')].map(i => i.decode().then(() => [i.naturalWidth, i.naturalHeight])))""")
    ok(f'photos were shrunk before upload {dims}', all(max(w, h) <= 1200 for w, h in dims))
    ok('the chosen cover (back photo, square) is first', dims[0][0] == dims[0][1])
    pg.get_by_label('Choose product photos').set_input_files(['e2e/img/box.webp'])
    pg.locator('figure').nth(2).wait_for()
    ok('add a third photo on the product page', pg.locator('figure').count() == 3)
    pg.locator('figure').nth(2).hover()
    pg.get_by_role('button', name='Remove photo 3').click()
    pg.wait_for_function("document.querySelectorAll('figure').length === 2")
    ok('remove a photo', True)
    pg.screenshot(path='shots/3-product-page.png', full_page=True)

    pg.goto(B + '/products')
    pg.locator('td img').first.wait_for()
    ok('product list shows the cover thumbnail', pg.locator('td img').count() >= 1)
    pg.screenshot(path='shots/4-products-list.png')
    pg.goto(B + '/pos')
    pg.get_by_label('Search products by name').fill('Galaxy')
    pg.locator('li img').first.wait_for()
    ok('POS search shows the photo', True)
    pg.screenshot(path='shots/5-pos-search.png')
    m = b.new_page(viewport={'width': 390, 'height': 844})
    b.close()
print('console errors:', [e for e in errs if '400' not in e])
print(f'{sum(res)} passed, {len(res) - sum(res)} failed'); sys.exit(0 if all(res) else 1)
